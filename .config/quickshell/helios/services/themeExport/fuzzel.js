// Fuzzel

// fuzzel wants RRGGBBAA with no leading "#".
function rgba(hex) { return String(hex).replace("#", "").slice(0, 6) + "ff"; }
function buildFuzzelTheme(p) {
    return "# Generated by Helios (Themes.qml) — do not edit by hand\n\n"
        + "[colors]\n"
        + "background=" + rgba(p.background) + "\n"
        + "text=" + rgba(p.text) + "\n"
        + "prompt=" + rgba(p.subtext) + "\n"
        + "placeholder=" + rgba(p.overlay) + "\n"
        + "input=" + rgba(p.text) + "\n"
        + "match=" + rgba(p.accent) + "\n"
        + "selection=" + rgba(p.accent) + "\n"
        + "selection-text=" + rgba(p.accentText) + "\n"
        + "selection-match=" + rgba(p.accentText) + "\n"
        + "counter=" + rgba(p.subtext) + "\n"
        + "border=" + rgba(p.accent) + "\n";
}

// Puts the include in the main section after any existing includes, so
// Helios colors win over an earlier theme include.
function withInclude(existing, includeLine) {
    const lines = (existing || "").split("\n");
    if (lines.some(line => line.trim() === includeLine)) return existing;
    let insertAt = 0;
    for (let i = 0; i < lines.length; i++) {
        const line = lines[i].trim();
        if (/^\[/.test(line) && line !== "[main]") break;
        if (/^include\s*=/.test(line) || line === "[main]") insertAt = i + 1;
    }
    lines.splice(insertAt, 0, includeLine);
    return lines.join("\n");
}

function exportTheme(p, ctx) {
    const themePath = ctx.home + "/.config/fuzzel/themes/helios";
    return {
        files: [
            { path: themePath, text: buildFuzzelTheme(p) },
            { path: ctx.home + "/.config/fuzzel/fuzzel.ini", text: withInclude(ctx.read(ctx.home + "/.config/fuzzel/fuzzel.ini"), "include=" + themePath) }
        ]
    };
}
